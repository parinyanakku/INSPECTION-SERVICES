import type { AppLanguage, DefectStatus, ProjectStatus, SeverityLevel } from '../types/inspection';

export const STORAGE_KEY_LANG = 'tis_wl_lang_v10';

export function translateSeverity(sev: SeverityLevel, lang: AppLanguage): string {
  if (lang === 'en') {
    if (sev === 'เร่งด่วน') return 'Urgent';
    if (sev === 'เล็กน้อย') return 'Minor';
    return 'Moderate';
  }
  return sev;
}

export function translateDefectStatus(status: DefectStatus, lang: AppLanguage): string {
  if (lang === 'en') {
    if (status === 'แก้ไขแล้ว') return 'Fixed';
    if (status === 'กำลังแก้ไข') return 'In Progress';
    return 'Pending';
  }
  return status;
}

export function translateProjectStatus(status: ProjectStatus, lang: AppLanguage): string {
  if (lang === 'en') {
    return status === 'ตรวจเสร็จสิ้น' ? 'Completed' : 'In Progress';
  }
  return status;
}

