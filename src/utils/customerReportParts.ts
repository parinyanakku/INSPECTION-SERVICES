// Encrypted report parts, never image transformation. A single short-link key
// authenticates the manifest and every numbered part with AES-GCM.
export const PART_SIZE=4*1024*1024;
export const MAX_REPORT_BYTES=512*1024*1024;
export const SINGLE_LIMIT=45*1024*1024;
export const MAX_PARTS=MAX_REPORT_BYTES/PART_SIZE;
export const MANIFEST_PREFIX='TIS-REPORT-PARTS-V1\n';
export function partPath(path:string,index:number){
 if(!/^[0-9a-f-]{36}\/[0-9a-f-]{36}\.bin$/.test(path)||!Number.isInteger(index)||index<0||index>=MAX_PARTS)throw Error('Invalid report part');
 return path.slice(0,-4)+'.part-'+String(index).padStart(3,'0')+'.bin';
}
export function partAAD(path:string,index:number){return new TextEncoder().encode('TIS-REPORT-PART-V1:'+path+':'+index);}
export async function encryptPayload(blob:Blob,aes:CryptoKey,aad?:Uint8Array){
 const iv=crypto.getRandomValues(new Uint8Array(12));
 const encrypted=await crypto.subtle.encrypt({name:'AES-GCM',iv,...(aad?{additionalData:aad as BufferSource}:{})},aes,await blob.arrayBuffer());
 return new Blob([iv,encrypted],{type:'application/octet-stream'});
}
export async function publishReportParts(blob:Blob,path:string,aes:CryptoKey,upload:(path:string,payload:Blob)=>Promise<void>,progress:(sent:number,total:number)=>void){
 if(!blob.size||blob.size>MAX_REPORT_BYTES)throw Error('รายงานเกิน 512 MiB หรือหน่วยความจำไม่เพียงพอ กรุณาแบ่งโครงการโดยไม่ลดคุณภาพรูป');
 if(blob.size+28<=SINGLE_LIMIT){await upload(path,await encryptPayload(blob,aes));progress(blob.size,blob.size);return 0;}
 const count=Math.ceil(blob.size/PART_SIZE);
 for(let i=0;i<count;i++){
  const end=Math.min((i+1)*PART_SIZE,blob.size);
  await upload(partPath(path,i),await encryptPayload(blob.slice(i*PART_SIZE,end),aes,partAAD(path,i)));progress(end,blob.size);
 }
 // Publish manifest last, so a partial upload cannot be opened.
 await upload(path,await encryptPayload(new Blob([MANIFEST_PREFIX+JSON.stringify({v:1,count,bytes:blob.size,partSize:PART_SIZE})]),aes));
 return count;
}

export const LAZY_PREFIX='TIS-REPORT-LAZY-V2\n';
// The source is generated by the app, not imported arbitrary HTML. Only the
// exact image attributes generated by the photo renderer are extracted.
export function separateReportPhotos(html:string){
 const assets:{offset:number;size:number}[]=[],blobs:Blob[]=[];let bytes=0;
 const shell=html.replace(/<img loading="lazy" alt="([^"]*)" src="(data:image\/(?:png|jpeg|jpg|webp|gif);base64,[a-z0-9+/=\s]+)">/gi,(_,alt,src)=>{
  const b=new Blob([src]);const index=assets.length;assets.push({offset:bytes,size:b.size});bytes+=b.size;blobs.push(b);
  return '<img loading="lazy" alt="'+alt+'" data-tis-asset="'+index+'">';
 });
 return {shell,assets,blob:new Blob(blobs),bytes};
}
const lazyScript=String.raw`
(function(){
 const imgs=Array.from(document.querySelectorAll('img[data-tis-asset]')),pending=new Set(),ready=new Set(),failed=new Set(),wantOpen=new Set();
 const en=document.documentElement.lang==='en';
 const label=(a,b)=>en?b:a;
 const ask=img=>{const id=Number(img.dataset.tisAsset);if(ready.has(id)||pending.has(id))return;pending.add(id);failed.delete(id);img.alt=label('กำลังโหลดรูป…','Loading photo…');parent.postMessage({type:'tis-photo-request',id},'*');};
 const byId=new Map(imgs.map(img=>[Number(img.dataset.tisAsset),img]));
 window.addEventListener('message',e=>{
  if(e.source!==parent||!e.data||e.data.type!=='tis-photo-result'||!Number.isInteger(e.data.id))return;
  const id=e.data.id,img=byId.get(id);if(!img||!pending.has(id))return;pending.delete(id);
  if(typeof e.data.src!=='string'||!/^data:image\/(?:png|jpeg|jpg|webp|gif);base64,[a-z0-9+/=\s]+$/i.test(e.data.src)){failed.add(id);img.alt=label('แตะเพื่อลองโหลดรูปใหม่','Tap to retry photo');return;}
  img.onload=()=>{ready.add(id);img.alt=img.closest('button')?.getAttribute('aria-label')||'';if(wantOpen.delete(id))img.closest('button')?.click();};
  img.onerror=()=>{ready.delete(id);failed.add(id);img.removeAttribute('src');img.alt=label('แตะเพื่อลองโหลดรูปใหม่','Tap to retry photo');};
  img.src=e.data.src;
 });
 document.addEventListener('click',e=>{const button=e.target.closest('button.photo'),img=button?.querySelector('img[data-tis-asset]');if(!img)return;const id=Number(img.dataset.tisAsset);if(!ready.has(id)){e.preventDefault();e.stopImmediatePropagation();wantOpen.add(id);ask(img);}},true);
 if('IntersectionObserver' in window){const io=new IntersectionObserver(entries=>{for(const entry of entries)if(entry.isIntersecting){io.unobserve(entry.target);ask(entry.target);}},{rootMargin:'250px'});imgs.forEach(img=>io.observe(img));}
 else {const scan=()=>{for(const img of imgs){const r=img.getBoundingClientRect();if(r.bottom>=-250&&r.top<=innerHeight+250&&!failed.has(Number(img.dataset.tisAsset)))ask(img);}};window.addEventListener('scroll',scan,{passive:true});scan();}
})();
`;
export async function publishLazyReport(html:string,path:string,aes:CryptoKey,upload:(path:string,payload:Blob)=>Promise<void>,progress:(sent:number,total:number)=>void){
 const split=separateReportPhotos(html);
 if(!split.assets.length)return publishReportParts(new Blob([html]),path,aes,upload,progress);
 const shell=split.shell.replace(/<\/body>\s*<\/html>$/i,'<script>'+lazyScript+'</script></body></html>');
 if(shell===split.shell)throw Error('Invalid report HTML');
 const count=Math.ceil(split.bytes/PART_SIZE),root=new Blob([LAZY_PREFIX+JSON.stringify({v:2,count,bytes:split.bytes,partSize:PART_SIZE,assets:split.assets,html:shell})]);
 if(count>MAX_PARTS||root.size+28>SINGLE_LIMIT||root.size+split.bytes>MAX_REPORT_BYTES)throw Error('รายงานเกินขีดจำกัด 512 MiB หรือส่วนข้อมูลหลักใหญ่เกิน 45 MiB');
 const total=split.bytes+root.size;
 for(let i=0;i<count;i++){const end=Math.min((i+1)*PART_SIZE,split.bytes);await upload(partPath(path,i),await encryptPayload(split.blob.slice(i*PART_SIZE,end),aes,partAAD(path,i)));progress(end,total);}
 await upload(path,await encryptPayload(root,aes));progress(total,total);return count;
}
